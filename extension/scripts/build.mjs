#!/usr/bin/env node
/**
 * build.mjs — keep the extension's copy of the page-side extractor honest.
 *
 * `web/src/lib/apply/extract-dom.mjs` is the ONE implementation of "read the
 * form / write an answer". The web app imports it directly; a content script
 * cannot import from outside the extension, so the file is copied here with its
 * `export` keywords stripped (a content script file is a classic script, and
 * its top-level function declarations become callable globals for the next file
 * Chrome injects in the same isolated world).
 *
 * The copy is generated, never edited: `--check` fails if it has drifted, which
 * is what stops the extension quietly growing a second, worse idea of what a
 * form field is.
 *
 *   node extension/scripts/build.mjs          # regenerate
 *   node extension/scripts/build.mjs --check  # verify (exit 1 on drift)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const EXT = resolve(HERE, '..');
const SOURCE = resolve(EXT, '..', 'web', 'src', 'lib', 'apply', 'extract-dom.mjs');
const TARGET = join(EXT, 'content', 'extract-dom.js');

const HEADER = `/* GENERATED by extension/scripts/build.mjs — DO NOT EDIT.
 * Source of truth: web/src/lib/apply/extract-dom.mjs
 * Run \`node extension/scripts/build.mjs\` after changing it. */
`;

/** Classic-script form: same code, minus the module syntax. */
export function toClassicScript(source) {
  return HEADER + source.replace(/^export (function|const|class) /gm, '$1 ');
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

// Guarded so importing this module (from a test) neither rewrites the file nor
// reads it: `toClassicScript` is the only thing a test needs.
if (isMain) {
  const generated = toClassicScript(readFileSync(SOURCE, 'utf8'));

  if (process.argv.includes('--check')) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
    if (current !== generated) {
      console.error('extension/content/extract-dom.js is stale — run: node extension/scripts/build.mjs');
      process.exit(1);
    }
    console.log('extension/content/extract-dom.js is in sync with web/src/lib/apply/extract-dom.mjs');
    process.exit(0);
  }

  writeFileSync(TARGET, generated);
  console.log(`wrote ${TARGET} (${generated.length} bytes)`);
}
